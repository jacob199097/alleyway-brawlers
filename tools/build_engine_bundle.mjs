// Bundles the game's rules and CPU (shared/clans.js, shared/duel/DuelState.js, shared/duel/DuelAI.js)
// into one browser script for the Card Forge's "Test this card": it defines window.AWB with an
// empty CARD_CATALOG the Forge fills with its own cards, so unsaved cards play by the real rules.
//
//   node tools/build_engine_bundle.mjs <out.js>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = process.argv[2];
if (!out) {
    console.error('usage: node tools/build_engine_bundle.mjs <out.js>');
    process.exit(2);
}

// Each module runs in its own scope; what it exports becomes a name the later ones can use
const MODULES = ['shared/clans.js', 'shared/duel/DuelState.js', 'shared/duel/DuelAI.js'];
const parts = ['// Generated by tools/build_engine_bundle.mjs from the game\'s rules: don\'t edit by hand.',
    '(() => {', 'const CARD_CATALOG = {};'];
const exported = new Set(['CARD_CATALOG']);
for (const file of MODULES) {
    let src = readFileSync(join(ROOT, file), 'utf8').replace(/\r\n/g, '\n');
    src = src.replace(/^import [^;]+;\n/gm, '');
    const names = [];
    src = src.replace(/^export (?:async )?(function|const|let|class) (\w+)/gm, (m, kind, name) => { names.push(name); return `${kind} ${name}`; });
    src = src.replace(/^export \{[^}]*\};?\n/gm, '');   // (re-exports of names already out)
    const fresh = names.filter(n => !exported.has(n));
    fresh.forEach(n => exported.add(n));
    const id = '__' + file.replace(/\W+/g, '_');
    parts.push(`// ── ${file}`, `const ${id} = (() => {`, src, `return { ${names.join(', ')} };`, '})();');
    if (fresh.length) parts.push(`const { ${fresh.join(', ')} } = ${id};`);
}
parts.push(`window.AWB = { ${[...exported].join(', ')} };`, '})();', '');
writeFileSync(out, parts.join('\n'));
console.log(`Wrote ${out} (${[...exported].length} names)`);
